"""(Re)create and seed the `items` table."""

import asyncio
import random
from datetime import datetime, timedelta, timezone

import asyncpg

from common import DSN, ROWS

SCHEMA = """
DROP TABLE IF EXISTS items;
CREATE TABLE items (
    id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       text NOT NULL,
    price      double precision NOT NULL,
    quantity   integer NOT NULL,
    tags       text[] NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now()
);
"""


async def main() -> None:
    rnd = random.Random(42)
    base = datetime(2026, 1, 1, tzinfo=timezone.utc)
    words = ["alpha", "beta", "gamma", "delta", "omega", "sigma", "kappa", "zeta"]
    records = [
        (
            i,
            f"item-{i:05d}-{rnd.choice(words)}",
            round(rnd.uniform(1, 1000), 2),
            rnd.randint(0, 500),
            rnd.sample(words, 3),
            base + timedelta(seconds=i * 37),
        )
        for i in range(1, ROWS + 1)
    ]
    conn = await asyncpg.connect(DSN)
    try:
        await conn.execute(SCHEMA)
        await conn.copy_records_to_table(
            "items",
            records=records,
            columns=["id", "name", "price", "quantity", "tags", "created_at"],
        )
        await conn.execute(f"SELECT setval(pg_get_serial_sequence('items', 'id'), {ROWS})")
        await conn.execute("VACUUM ANALYZE items")
    finally:
        await conn.close()
    print(f"seeded {ROWS} rows")


if __name__ == "__main__":
    asyncio.run(main())
